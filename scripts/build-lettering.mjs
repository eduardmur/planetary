#!/usr/bin/env node
// Extracts the single-stroke Hershey Sans glyphs the drawings use into src/draw/lettering-data.ts.
// Source: HersheySans1.svg from the hersheytext package (Evil Mad Scientist's conversion of the
// Hershey fonts). Run after changing the character set: node scripts/build-lettering.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
// Pinned source of the glyphs; the generated module is committed, so this runs only when the
// character set changes.
const SOURCE = 'https://unpkg.com/hersheytext@2.0.0/svg_fonts/HersheySans1.svg';
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const svg = await res.text();

/** Cap height of the source glyphs (font units); output coordinates are in cap heights. */
const CAP = 662;

const decode = (u) =>
  u
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&amp;/g, '&')
    .replace(/&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>');

const WANT = new Set(
  [
    ...'!"#%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[]_abcdefghijklmnopqrstuvwxyz|~ ',
  ].concat(['°', '±', '·', '×', 'Ø', 'é', '–', '—', '“', '”']),
);

const glyphs = {};
for (const m of svg.matchAll(
  /<glyph unicode="([^"]*)"[^>]*?horiz-adv-x="([\d.]+)"(?:[^>]*?d="([^"]*)")?/g,
)) {
  const ch = decode(m[1]);
  if (!WANT.has(ch)) continue;
  const adv = +m[2];
  const strokes = [];
  if (m[3]) {
    let cur = null;
    const tokens = m[3].trim().split(/\s+/);
    for (let i = 0; i < tokens.length;) {
      const t = tokens[i];
      if (t === 'M' || t === 'L') {
        const x = +tokens[i + 1],
          y = +tokens[i + 2];
        if (t === 'M') strokes.push((cur = []));
        cur.push([x, y]);
        i += 3;
      } else throw new Error(`unexpected token ${t} in glyph ${ch}`);
    }
  }
  const enc = strokes
    .map((s) => s.map(([x, y]) => `${(x / CAP).toFixed(3)},${(y / CAP).toFixed(3)}`).join(' '))
    .join('|');
  glyphs[ch] = [+(adv / CAP).toFixed(3), enc];
}

const missing = [...WANT].filter((c) => !(c in glyphs));
if (missing.length) throw new Error(`missing glyphs: ${missing.join(' ')}`);

const header = `// Generated by scripts/build-lettering.mjs — do not edit.
//
// Single-stroke glyphs from the Hershey Sans 1-stroke font (HersheySans1.svg, hersheytext package).
// Coordinates are in cap heights, y up, origin at the left end of the baseline. Each entry is
// [advance, "x,y x,y|x,y …"] with strokes separated by "|".
//
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
// U. S. National Bureau of Standards.
// The format of the Font data in this distribution was originally created by
//   James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821
//   (mit-eddie!ci-dandelion!hurt)
// SVG font conversion by Windell H. Oskay, www.evilmadscientist.com.
`;
const body = `export const GLYPHS: Record<string, [number, string]> = ${JSON.stringify(
  glyphs,
  null,
  0,
)
  .replace(/\],"/g, '],\n  "')
  .replace(/^\{/, '{\n  ')
  .replace(/\}$/, ',\n}')};\n`;
writeFileSync(resolve(root, 'src/draw/lettering-data.ts'), header + '\n' + body);
console.log(`${Object.keys(glyphs).length} glyphs → src/draw/lettering-data.ts`);
